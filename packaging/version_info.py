"""exe 파일 버전 정보(v3.1 설계 D45): 탐색기 속성·작업 관리자·오류 보고에서 빌드를 가린다.

`evolab.spec`이 빌드 때 불러 두 exe(evolab.exe, evolab-cli.exe)마다 PyInstaller 버전 정보 파일을 만들고 `EXE(version=…)`로
넣는다. 파일은 PyInstaller `VSVersionInfo`의 글 표현(PyInstaller가 `eval`로 읽는 형식)이다. PyInstaller의 versioninfo 모듈은
윈도우 전용 의존성(pefile, pywin32)을 불러서 리눅스에서 import되지 않으므로 글을 직접 만든다(리눅스 빌드는 버전 정보를 무시한다).

- 파일 버전·제품 버전 = pyproject 버전 네 칸(3.1.0 → 3.1.0.0), 제품 이름·설명 = strings.py `APP_NAME`, 회사 = `INST_PUBLISHER`.
- 문자열 표는 한국어·유니코드(0x0412, 코드 페이지 1200).
"""

from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path
from typing import Final

ROOT: Final = Path(__file__).resolve().parent.parent
EXE_NAMES: Final = ("evolab", "evolab-cli")
LANG_KOREAN: Final = 0x0412
CODEPAGE_UNICODE: Final = 1200


def project_version(root: Path = ROOT) -> str:
    """pyproject.toml의 `[project].version`(X.Y.Z)."""
    version = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))["project"]["version"]
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise ValueError(f"version must look like 3.1.0, not {version!r}")
    return version


def numeric_version(version: str) -> tuple[int, int, int, int]:
    """3.1.0 → (3, 1, 0, 0). 각 칸은 0..65535(윈도우 버전 정보 한 칸이 16비트)."""
    parts = [int(p) for p in version.split(".")]
    if not 1 <= len(parts) <= 4 or any(not 0 <= p <= 0xFFFF for p in parts):
        raise ValueError(f"bad version {version!r}")
    return tuple(parts + [0] * (4 - len(parts)))  # type: ignore[return-value]


def _strings():
    src = str(ROOT / "src")
    if src not in sys.path:
        sys.path.insert(0, src)
    from evolab.app import strings as S

    return S


def version_info_text(exe_name: str, version: str | None = None) -> str:
    """PyInstaller 버전 정보 파일 글(`VSVersionInfo(...)`). exe_name은 확장자 없는 이름(evolab, evolab-cli)."""
    S = _strings()
    version = project_version() if version is None else version
    nums = numeric_version(version)
    dotted = ".".join(str(n) for n in nums)
    table = f"{LANG_KOREAN:04X}{CODEPAGE_UNICODE:04X}"
    strings = [
        ("CompanyName", S.INST_PUBLISHER),
        ("FileDescription", S.APP_NAME),
        ("FileVersion", dotted),
        ("InternalName", exe_name),
        ("OriginalFilename", f"{exe_name}.exe"),
        ("ProductName", S.APP_NAME),
        ("ProductVersion", version),
    ]
    rows = ",\n".join(f"          StringStruct({name!r}, {value!r})" for name, value in strings)
    return (
        "# UTF-8\n"
        "# Generated by packaging/version_info.py (evolab.spec). Do not edit.\n"
        "VSVersionInfo(\n"
        "  ffi=FixedFileInfo(\n"
        f"    filevers={nums!r},\n"
        f"    prodvers={nums!r},\n"
        "    mask=0x3f,\n"
        "    flags=0x0,\n"
        "    OS=0x40004,\n"
        "    fileType=0x1,\n"
        "    subtype=0x0,\n"
        "    date=(0, 0)\n"
        "  ),\n"
        "  kids=[\n"
        "    StringFileInfo([\n"
        "      StringTable(\n"
        f"        {table!r},\n"
        "        [\n"
        f"{rows}\n"
        "        ])\n"
        "    ]),\n"
        f"    VarFileInfo([VarStruct('Translation', [{LANG_KOREAN}, {CODEPAGE_UNICODE}])])\n"
        "  ]\n"
        ")\n"
    )


def write_version_files(out_dir: Path, version: str | None = None) -> dict[str, Path]:
    """exe마다 버전 정보 파일을 out_dir에 쓰고 {exe 이름: 경로}를 돌려준다(UTF-8 BOM: PyInstaller가 BOM을 보고 읽는다)."""
    out_dir.mkdir(parents=True, exist_ok=True)
    version = project_version() if version is None else version
    files = {}
    for name in EXE_NAMES:
        path = out_dir / f"version_info_{name}.txt"
        path.write_bytes(b"\xef\xbb\xbf" + version_info_text(name, version).encode("utf-8"))
        files[name] = path
    return files
